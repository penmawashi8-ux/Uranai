def _validate_message(msg: str) -> bool:
    """ネガティブワードが含まれていないか確認する。"""
    for word in NEGATIVE_WORDS:
        if word in msg:
            return False
    return True


def get_fortune_cards(date: datetime | None = None) -> list[dict]:
    """
    日付ベースのシードで3枚のカードを選択して返す。

    カード15種 × メッセージ6件 × カラー25種 × アイテム30種の
    組み合わせにより事実上毎日異なるコンテンツを生成する。

    Returns:
        [
            {"title": str, "symbol": str, "rank": int, "message": str,
             "lucky_color": str, "lucky_item": str},
            ...
        ]  ランク順（1が最良）でソートされている
    """
    if date is None:
        date = datetime.now()

    # 年・月・日・曜日すべてをシードに混ぜてより多様に
    seed = int(date.strftime("%Y%m%d")) * 7 + date.weekday()
    rng = random.Random(seed)

    # 3枚選択（IDではなくインデックスで重複排除）
    selected = rng.sample(CARD_POOL, 3)

    # メッセージ選択（rng を使って真にランダム）
    cards = []
    for tpl in selected:
        msg = rng.choice(tpl["messages"])
        assert _validate_message(msg), f"Negative word in message: {msg}"
        cards.append(
            {
                "title": tpl["title"],
                "symbol": tpl["symbol"],
                "rank": 0,  # 後で設定
                "message": msg,
            }
        )

    # ランク割り当て（シードに基づく順列）
    ranks = rng.sample([1, 2, 3], 3)
    for i, card in enumerate(cards):
        card["rank"] = ranks[i]

    # ラッキーカラー・アイテム割り当て（重複なし）
    color_indices = rng.sample(range(len(LUCKY_COLORS)), 3)
    item_indices = rng.sample(range(len(LUCKY_ITEMS)), 3)
    for i, card in enumerate(cards):
        card["lucky_color"] = LUCKY_COLORS[color_indices[i]]
        card["lucky_item"] = LUCKY_ITEMS[item_indices[i]]

    # ランク順にソート
    cards.sort(key=lambda c: c["rank"])
    return cards


def get_date_string(date: datetime | None = None) -> str:
    """日本語の日付文字列を返す（例: 4月11日）。"""
    if date is None:
        date = datetime.now()
    return f"{date.month}月{date.day}日"


